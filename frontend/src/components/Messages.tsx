interface ErrorProps {
  message: string
  status: number | null
  retried?: boolean
  onRetry: () => void
  onRestore: () => void
  disabled: boolean
}

export function ErrorMessage({ message, status, retried, onRetry, onRestore, disabled }: ErrorProps) {
  return (
    <div className="flex animate-fade-up gap-3" role="alert">
      <div className="mt-0.5 flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-rose-500/15 text-rose-300" aria-hidden>
        <AlertTriangle className="h-3.5 w-3.5" />
      </div>
      <div
        data-testid="error-message"
        className="min-w-0 max-w-full flex-1 rounded-2xl rounded-tl-md border border-rose-500/30 bg-rose-500/[0.07] px-4 py-3 sm:max-w-[85%] sm:flex-none"
      >
        <div className="mb-1 flex items-center gap-2 font-mono text-[11px] uppercase tracking-wide text-rose-300/80">
          <span>Request failed</span>
          {status != null && <span className="rounded bg-rose-500/15 px-1.5 py-px">HTTP {status}</span>}
          {status == null && <span className="rounded bg-rose-500/15 px-1.5 py-px">network</span>}
        </div>
        <p className="whitespace-pre-wrap break-words text-sm leading-relaxed text-rose-100">{message}</p>
        {!retried && (
          <div className="mt-3 flex flex-wrap gap-2">
            <button
              type="button"
              onClick={onRetry}
              disabled={disabled}
              className="inline-flex items-center gap-1.5 rounded-md border border-rose-400/30 bg-rose-500/10 px-2.5 py-1 text-xs font-medium text-rose-100 transition hover:bg-rose-500/20 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-rose-400 disabled:cursor-not-allowed disabled:opacity-50"
            >
              <RotateCcw className="h-3.5 w-3.5" aria-hidden />
              Retry
            </button>
            <button
              type="button"
              onClick={onRestore}
              className="inline-flex items-center gap-1.5 rounded-md border border-zinc-700 bg-zinc-900 px-2.5 py-1 text-xs font-medium text-zinc-300 transition hover:bg-zinc-800 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-indigo-500"
            >
              <ArrowDownToLine className="h-3.5 w-3.5" aria-hidden />
              Edit message
            </button>
          </div>
        )}
      </div>
    </div>
  )
}

