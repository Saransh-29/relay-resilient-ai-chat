function Avatar() {
  return (
    <div
      className="mt-0.5 flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-gradient-to-br from-indigo-500 to-violet-600 text-white shadow-md shadow-indigo-500/20"
      aria-hidden
    >
      <Bot className="h-3.5 w-3.5" />
    </div>
  )
}

function Sep() {
  return <span className="hidden h-3 w-px bg-zinc-800 sm:inline-block" aria-hidden />
}

export function MetaRow({ metadata }: { metadata: ChatMetadata }) {
  const isCache = metadata.resolution_source === 'LLM_CACHE'
  const fallback = Number(metadata.fallback_attempts) || 0

  return (
    <div className="mt-3 flex flex-wrap items-center gap-x-3 gap-y-2 border-t border-zinc-800/80 pt-2.5 font-mono text-[11px] text-zinc-400">
      <span
        className={`inline-flex items-center gap-1.5 rounded-md border px-2 py-0.5 font-medium ${
          isCache ? 'border-emerald-500/30 bg-emerald-500/10 text-emerald-300' : 'border-sky-500/30 bg-sky-500/10 text-sky-300'
        }`}
        title={isCache ? 'Served from LiteLLM response cache' : 'Generated by a live model call'}
      >
        {isCache ? (
          <>
            <Database className="h-3 w-3" aria-hidden />
            <Zap className="-ml-1 h-3 w-3" aria-hidden />
          </>
        ) : (
          <Cpu className="h-3 w-3" aria-hidden />
        )}
        <span data-testid="meta-source">{metadata.resolution_source}</span>
      </span>

      <span className="inline-flex min-w-0 items-center gap-1" title="Model">
        <span className="text-zinc-600">model</span>
        <span data-testid="meta-model" className="max-w-[14rem] truncate text-zinc-300">
          {metadata.model}
        </span>
      </span>
      <Sep />
      <span className="inline-flex items-center gap-1" title="Server-measured latency">
        <Clock className="h-3 w-3 text-zinc-600" aria-hidden />
        <span data-testid="meta-latency" className="text-zinc-300">
          {metadata.latency_ms} ms
        </span>
      </span>
      <Sep />
      <span className="inline-flex items-center gap-1" title="Tokens for this request only (input / output)">
        <span className="text-zinc-600">in</span>
        <span data-testid="meta-input-tokens" className="text-zinc-300">
          {metadata.input_tokens}
        </span>
        <span className="text-zinc-700">/</span>
        <span className="text-zinc-600">out</span>
        <span data-testid="meta-output-tokens" className="text-zinc-300">
          {metadata.output_tokens}
        </span>
      </span>
      <Sep />
      <span className="inline-flex items-center gap-1" title="Key that answered (null on cache hits)">
        <KeyRound className="h-3 w-3 text-zinc-600" aria-hidden />
        <span data-testid="meta-key-id" className="text-zinc-300">
          {metadata.key_id ?? 'null'}
        </span>
      </span>
      {fallback > 0 && (
        <span
          className="inline-flex items-center gap-1 rounded-md border border-amber-500/30 bg-amber-500/10 px-2 py-0.5 font-medium text-amber-300"
          title={`${fallback} key(s) failed before ${metadata.key_id ?? 'a key'} succeeded`}
        >
          <Shuffle className="h-3 w-3" aria-hidden />
          <span>
            fallback ×<span data-testid="meta-fallback-attempts">{fallback}</span>
          </span>
        </span>
      )}
    </div>
  )
}

